"""Write docs/results.md from the benchmark output, so its numbers can't drift from it.

    python -m abyss.evaluation.report

The findings' wording reflects the results as run. If the benchmark changes, rerun this,
then reread and correct the wording rather than trusting it.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

PLANNER_NAMES = {
    "abyss": "ABYSS",
    "frontier": "Frontier",
    "lawnmower": "Lawnmower",
    "heuristic": "Heuristic",
    "random": "Random",
    "abyss-noinfo": "No uncertainty",
    "abyss-nolearn": "No learning",
}
WORLD_NAMES = {
    "random": "Independent random",
    "clustered": "Spatial clusters",
    "ridge": "Ridge-associated",
    "reversed": "Flat-associated",
    "nonlinear": "Nonlinear mixed",
}
TERRAIN_NAMES = {"gebco": "GEBCO Monterey Canyon crop", "synthetic": "Synthetic terrain, one per seed"}


def _label(world: dict) -> str:
    name = WORLD_NAMES[world["scenario"]]
    return name if world["scenario"] == "random" else f"{name}, signal {world['rho']:g}"


def _diff(data: dict, other: str, scenario: str, rho: float, terrain: str = "gebco") -> str:
    world = next(
        w for w in data["worlds"]
        if (w["terrain"], w["scenario"], w["rho"]) == (terrain, scenario, rho)
    )
    c = world["abyss_vs"][other]
    return f"{c['mean_difference']:+.2f} [{c['ci95_low']:+.2f}, {c['ci95_high']:+.2f}]"


def _means_table(data: dict, terrain: str) -> list[str]:
    planners = list(PLANNER_NAMES)
    lines = [
        "| World | " + " | ".join(PLANNER_NAMES[p] for p in planners) + " |",
        "| --- |" + " --- |" * len(planners),
    ]
    for world in (w for w in data["worlds"] if w["terrain"] == terrain):
        means = [world["planners"][p]["mean"] for p in planners]
        lines.append(f"| {_label(world)} | " + " | ".join(f"{m:.2f}" for m in means) + " |")
    return lines


def _comparison_table(data: dict, terrain: str) -> list[str]:
    others = [p for p in PLANNER_NAMES if p != "abyss"]
    lines = [
        "| World | " + " | ".join(f"vs {PLANNER_NAMES[p]}" for p in others) + " |",
        "| --- |" + " --- |" * len(others),
    ]
    for world in (w for w in data["worlds"] if w["terrain"] == terrain):
        cells = []
        for other in others:
            c = world["abyss_vs"][other]
            mark = "**" if c["ci95_low"] > 0 or c["ci95_high"] < 0 else ""
            cells.append(f"{mark}{c['mean_difference']:+.2f}{mark} [{c['ci95_low']:+.2f}, {c['ci95_high']:+.2f}]")
        lines.append(f"| {_label(world)} | " + " | ".join(cells) + " |")
    return lines


def render(data: dict) -> str:
    safety = data["safety"]
    categories = data["frozen_config"]["simulation"]["n_categories"]
    frozen = data["frozen_config"]["abyss"]

    def d(*args, **kwargs) -> str:
        return _diff(data, *args, **kwargs)

    lines = [
        "# ABYSS benchmark results",
        "",
        "Generated by `python -m abyss.evaluation.report` from executed missions. Regenerate it",
        "rather than editing it by hand.",
        "",
        f"**Setup:** {safety['missions']} missions on evaluation seeds {data['seeds'][0]} to {data['seeds'][-1]}, with",
        f"{safety['safe_returns']} safe returns and {safety['forced_returns']} forced returns. Each planner gets the same",
        f"worlds, energy budget and sensing. The metric is distinct categories found within the budget, out of {categories},",
        "scored on true labels. Differences are ABYSS minus the other planner: the mean, then a 95% paired bootstrap interval.",
        f"ABYSS's weights (beta {frozen['beta']:g}, gamma {frozen['gamma']:g}) were frozen on development seeds before this run.",
        "",
        "## Findings",
        "",
        "Differences use the GEBCO crop unless they say otherwise. **No planner wins everywhere.**",
        "",
        "1. **ABYSS clearly gains on ridge-associated worlds, and the gain grows with the signal.** Against",
        f"   frontier: {d('frontier', 'ridge', 0.25)} at signal 0.25 and {d('frontier', 'ridge', 1.0)} at signal 1. Against",
        f"   lawnmower: {d('lawnmower', 'ridge', 0.25)} and {d('lawnmower', 'ridge', 1.0)}.",
        "2. **A plain lawnmower beats ABYSS on flat-associated worlds on the real crop.** ABYSS minus lawnmower is",
        f"   {d('lawnmower', 'reversed', 0.25)} at signal 0.25, {d('lawnmower', 'reversed', 0.5)} at 0.5 and",
        f"   {d('lawnmower', 'reversed', 1.0)} at 1. Cam's analysis points to the target: the model predicts richness,",
        "   not novelty, so it can keep returning to rich habitat full of known organisms. On synthetic terrain the",
        f"   same comparison favours ABYSS at signal 1: {d('lawnmower', 'reversed', 1.0, terrain='synthetic')}.",
        "3. **With no structure to learn, learning costs something on the real crop.** In the random world, ABYSS is",
        f"   behind frontier by {d('frontier', 'random', 0.0)} and behind its no-learning version by",
        f"   {d('abyss-nolearn', 'random', 0.0)}. On synthetic terrain neither gap is clear:",
        f"   {d('frontier', 'random', 0.0, terrain='synthetic')} and {d('abyss-nolearn', 'random', 0.0, terrain='synthetic')}.",
        f"4. **Spatial clusters give a mixed result.** ABYSS beats frontier by {d('frontier', 'clustered', 1.0)}, but",
        f"   shows no clear difference from lawnmower: {d('lawnmower', 'clustered', 1.0)}.",
        "5. **Learning protects against a wrong assumption, but a right assumption is hard to beat.** Against the fixed",
        f"   steep-ground rule: {d('heuristic', 'reversed', 1.0)} on flat-associated worlds at signal 1, but",
        f"   {d('heuristic', 'ridge', 0.5)} at ridge signal 0.5 and {d('heuristic', 'nonlinear', 1.0)} on the nonlinear world.",
        "6. **The uncertainty term rarely shows a clear effect on the real crop.** ABYSS minus its no-uncertainty version is",
        f"   {d('abyss-noinfo', 'ridge', 0.25)} at ridge signal 0.25, with most other worlds unclear. On synthetic terrain",
        f"   it is {d('abyss-noinfo', 'ridge', 0.5, terrain='synthetic')} at ridge signal 0.5.",
        "",
        "## Limitations",
        "",
        "- **Biology is simulated.** These results show behaviour in worlds we designed, not real",
        "  ocean ecology. Several worlds use features ABYSS's model can represent, which helps it.",
        "- **Ideal perception only.** These runs use simulator labels. The planned comparison of ideal",
        "  and real perception has not been run.",
        "- **One real terrain crop.** GEBCO seeds share one crop, so they vary the biology but not the",
        "  region. Synthetic terrain varies by seed, but it isn't real bathymetry. The two disagree",
        "  in places, so terrain shape matters.",
        "- **Ceiling effects.** Results near the maximum category count understate differences.",
        "- **Many comparisons.** Intervals are not corrected for multiple comparisons, so treat",
        "  borderline results with caution.",
        "- **Simple target.** The model predicts richness rather than new categories.",
        "- **Abstract energy.** Energy units and travel costs are not measured from a real vehicle.",
        "",
    ]
    for terrain in TERRAIN_NAMES:
        lines += [f"## {TERRAIN_NAMES[terrain]}", "", "Mean categories found:", ""]
        lines += _means_table(data, terrain)
        lines += ["", "ABYSS minus each planner. Bold means the 95% interval excludes zero:", ""]
        lines += _comparison_table(data, terrain)
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--summary", type=Path, default=Path("ui/logs/benchmark.json"))
    parser.add_argument("--out", type=Path, default=Path("docs/results.md"))
    args = parser.parse_args()
    data = json.loads(args.summary.read_text(encoding="utf-8"))
    args.out.write_text(render(data), encoding="utf-8")
    print(f"Wrote {args.out}")


if __name__ == "__main__":
    main()
